#!/usr/bin/env node
// Export pinned Skill bodies; consumers need no separate Skill installation.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repository = "https://github.com/coder-xieshijie/dev-skills";
const names = ["explain-as-fool", "review-rules", "plan-for-agents"];
const manifestPath = path.join(root, "references/skill-rules.json");
const hash = (text) => createHash("sha256").update(text).digest("hex");
const args = process.argv.slice(2);
const check = args.includes("--check");
const sourceIndex = args.indexOf("--source");
const revisionIndex = args.indexOf("--revision");

try {
  if (check && args.length === 1) {
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (
      manifest.repository !== repository ||
      !/^[0-9a-f]{40}$/.test(manifest.revision) ||
      manifest.files?.length !== names.length
    )
      throw new Error("invalid skill-rules manifest");
    for (const [index, name] of names.entries()) {
      const entry = manifest.files[index];
      if (
        entry.source !== `skills/${name}/SKILL.md` ||
        entry.target !== `references/${name}.md` ||
        !/^[0-9a-f]{64}$/.test(entry.source_sha256) ||
        hash(readFileSync(path.join(root, entry.target))) !== entry.sha256
      )
        throw new Error(
          `${name}: bundled rules changed; regenerate from the source`,
        );
    }
    console.log(`skill-rules: ${names.length} pinned copies verified`);
  } else if (
    !check &&
    args.length === 4 &&
    sourceIndex >= 0 &&
    revisionIndex >= 0 &&
    sourceIndex % 2 === 0 &&
    revisionIndex % 2 === 0
  ) {
    const source = args[sourceIndex + 1];
    const ref = args[revisionIndex + 1];
    const git = (...command) =>
      execFileSync("git", ["-C", source, ...command], { encoding: "utf8" });
    const origin = git("remote", "get-url", "origin").trim();
    if (
      ![
        repository,
        `${repository}.git`,
        "git@github.com:coder-xieshijie/dev-skills.git",
      ].includes(origin)
    )
      throw new Error("source must be the dev-skills repository");
    const revision = git(
      "rev-parse",
      "--verify",
      "--end-of-options",
      `${ref}^{commit}`,
    ).trim();
    // Read all inputs from the commit before writing anything. Dirty checkout
    // contents cannot silently enter a supposedly pinned snapshot.
    const outputs = names.map((name) => {
      const sourcePath = `skills/${name}/SKILL.md`;
      const original = git("show", `${revision}:${sourcePath}`);
      const match = original.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n([\s\S]*)$/);
      if (!match?.[1].trim())
        throw new Error(`${sourcePath}: missing Skill body`);
      const text = `<!-- Generated by scripts/sync-skill-rules.mjs; edit the upstream Skill, then sync. -->\n\nSource: [${name}](${repository}/blob/${revision}/${sourcePath}) at \`${revision}\`.\nRead these bundled rules directly; no separate Skill invocation or installation is required.\n\n${match[1].trim()}\n`;
      return {
        source: sourcePath,
        target: `references/${name}.md`,
        source_sha256: hash(original),
        sha256: hash(text),
        text,
      };
    });
    mkdirSync(path.dirname(manifestPath), { recursive: true });
    for (const output of outputs)
      writeFileSync(path.join(root, output.target), output.text);
    writeFileSync(
      manifestPath,
      JSON.stringify(
        {
          repository,
          revision,
          files: outputs.map(({ text, ...entry }) => entry),
        },
        null,
        2,
      ) + "\n",
    );
    console.log(
      `skill-rules: exported ${names.length} copies from ${revision}`,
    );
  } else {
    throw new Error(
      "usage: sync-skill-rules.mjs --check | --source <dev-skills checkout> --revision <commit/ref>",
    );
  }
} catch (error) {
  console.error(`skill-rules: ${error.message}`);
  process.exitCode = 1;
}
